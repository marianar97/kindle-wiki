#!/usr/bin/env python3
"""Sync Kindle highlights from My Clippings.txt into vault/books/*.md."""
from __future__ import annotations

import argparse
import hashlib
import json
import re
import shutil
import sys
from dataclasses import dataclass
from datetime import datetime
from pathlib import Path

SEPARATOR_RE = re.compile(r"(?m)^={10,}\r?$")
DATE_FMT = "%A, %B %d, %Y %I:%M:%S %p"
TITLE_RE = re.compile(r"^(?P<title>.*?)(?:\s*\((?P<author>[^()]*)\))?\s*$")
META_RE = re.compile(
    r"^- Your (?P<type>Highlight|Note|Bookmark)"
    r"(?: on page (?P<page>[^|]+?))?"
    r"(?:\s*\|?\s*(?:at )?location (?P<location>[\d-]+))?"
    r"(?:\s*\|\s*Added on (?P<date>.+))?$"
)
LAST_SYNCED_RE = re.compile(r"^last_synced: .*$", re.MULTILINE)
BLOCK_ID_RE = re.compile(r"\^([0-9a-f]{12})")


@dataclass
class Clip:
    title: str
    author: str | None
    type: str  # "highlight" | "note" | "bookmark"
    page: str | None
    location: str | None
    date: datetime | None
    text: str

    @property
    def id(self) -> str:
        key = f"{self.title}|{self.type}|{self.location}|{self.text}"
        return hashlib.sha1(key.encode("utf-8")).hexdigest()[:12]


def parse_entry(block: str) -> Clip | None:
    lines = [line.rstrip("\r") for line in block.split("\n")]
    while lines and not lines[0].strip():
        lines.pop(0)
    while lines and not lines[-1].strip():
        lines.pop()
    if len(lines) < 2:
        return None
    m_title = TITLE_RE.match(lines[0].lstrip("﻿"))
    m_meta = META_RE.match(lines[1])
    if not m_title or not m_meta:
        return None
    date = None
    if m_meta.group("date"):
        try:
            date = datetime.strptime(m_meta.group("date").strip(), DATE_FMT)
        except ValueError:
            pass
    page = m_meta.group("page")
    author = (m_title.group("author") or "").strip()
    return Clip(
        title=m_title.group("title").strip(),
        author=author or None,
        type=m_meta.group("type").lower(),
        page=page.strip() if page else None,
        location=m_meta.group("location"),
        date=date,
        text="\n".join(lines[2:]).strip(),
    )


def parse_clippings(text: str) -> list[Clip]:
    clips = []
    for block in SEPARATOR_RE.split(text.lstrip("﻿")):
        clip = parse_entry(block)
        if clip is not None:
            clips.append(clip)
    return clips


def dedupe(clips: list[Clip]) -> list[Clip]:
    best: dict[str, Clip] = {}
    order: list[str] = []
    for clip in clips:
        cid = clip.id
        if cid not in best:
            best[cid] = clip
            order.append(cid)
        elif (clip.date or datetime.min) > (best[cid].date or datetime.min):
            best[cid] = clip
    return [best[cid] for cid in order]


TYPE_RANK = {"highlight": 0, "note": 1, "bookmark": 2}


def location_start(clip: Clip) -> int:
    if not clip.location:
        return 0
    return int(clip.location.split("-")[0])


def group_books(clips: list[Clip]) -> dict[tuple[str, str | None], list[Clip]]:
    books: dict[tuple[str, str | None], list[Clip]] = {}
    for clip in clips:
        books.setdefault((clip.title, clip.author), []).append(clip)
    for key in books:
        books[key].sort(key=lambda c: (location_start(c), TYPE_RANK[c.type]))
    return books


def meta_parts(clip: Clip) -> list[str]:
    parts = []
    if clip.page:
        parts.append(f"p. {clip.page}")
    if clip.location:
        parts.append(f"loc. {clip.location}")
    if clip.date:
        parts.append(clip.date.strftime("%Y-%m-%d"))
    return parts


def meta_line(clip: Clip) -> str:
    return " · ".join([clip.type] + meta_parts(clip))


def render_clip(clip: Clip) -> str:
    if clip.type == "highlight":
        quoted = "\n".join(f"> {line}" for line in clip.text.split("\n"))
        return f"{quoted}\n>\n> — {meta_line(clip)} ^{clip.id}"
    if clip.type == "note":
        return f"Note: {clip.text}\n— {meta_line(clip)} ^{clip.id}"
    return f"{' · '.join(['Bookmark'] + meta_parts(clip))} ^{clip.id}"


GENERATED_NOTE = (
    "<!-- GENERATED by sync.py — edits are overwritten on every Kindle sync -->"
)


def slugify(title: str) -> str:
    slug = re.sub(r"[^a-z0-9]+", "-", title.lower()).strip("-")
    return slug or "untitled"


def render_book(
    title: str, author: str | None, clips: list[Clip], synced_on: str
) -> str:
    lines = [
        "---",
        f"title: {json.dumps(title, ensure_ascii=False)}",
        f"author: {json.dumps(author, ensure_ascii=False) if author else 'null'}",
        f"last_synced: {synced_on}",
        "---",
        GENERATED_NOTE,
        "",
        f"# {title}",
    ]
    if author:
        lines.append(f"*{author}*")
    lines += ["", "## Highlights", ""]
    body = "\n\n".join(render_clip(c) for c in clips)
    return "\n".join(lines) + f"\n{body}\n"


def _strip_volatile(text: str) -> str:
    return LAST_SYNCED_RE.sub("last_synced:", text)


def write_vault(
    books: dict[tuple[str, str | None], list[Clip]],
    vault_dir: Path,
    synced_on: str,
) -> tuple[int, int]:
    vault_dir.mkdir(parents=True, exist_ok=True)
    new_clips, changed_books = 0, 0
    used: set[str] = set()
    for (title, author), clips in sorted(books.items(), key=lambda kv: kv[0][0]):
        slug = slugify(title)
        if slug in used:
            slug = f"{slug}-{slugify(author or clips[0].id)}"
        used.add(slug)
        path = vault_dir / f"{slug}.md"
        content = render_book(title, author, clips, synced_on)
        old = path.read_text(encoding="utf-8") if path.exists() else ""
        if _strip_volatile(old) == _strip_volatile(content):
            continue
        old_ids = set(BLOCK_ID_RE.findall(old))
        new_clips += sum(1 for c in clips if c.id not in old_ids)
        tmp = path.with_suffix(".md.tmp")
        tmp.write_text(content, encoding="utf-8")
        tmp.replace(path)
        changed_books += 1
    return new_clips, changed_books


DEFAULT_SOURCE = Path("/Volumes/Kindle/documents/My Clippings.txt")


def run(source: Path, root: Path) -> int:
    if not source.exists():
        print(f"Clippings file not found: {source}", file=sys.stderr)
        print("Is the Kindle plugged in?", file=sys.stderr)
        return 1
    copies = root / "data" / "clippings"
    copies.mkdir(parents=True, exist_ok=True)
    stamp = datetime.now().strftime("%Y-%m-%d-%H%M%S")
    copy_path = copies / f"{stamp}-My Clippings.txt"
    shutil.copy2(source, copy_path)
    clips = dedupe(parse_clippings(copy_path.read_text(encoding="utf-8")))
    books = group_books(clips)
    synced_on = datetime.now().strftime("%Y-%m-%d")
    new_clips, changed = write_vault(books, root / "vault" / "books", synced_on)
    print(
        f"{new_clips} new clips across {changed} books "
        f"({len(clips)} clips in {len(books)} books total)"
    )
    return 0


def main(argv: list[str] | None = None) -> int:
    parser = argparse.ArgumentParser(
        description="Sync Kindle clippings into the Obsidian vault."
    )
    parser.add_argument(
        "source", nargs="?", type=Path, default=DEFAULT_SOURCE,
        help="path to My Clippings.txt (default: mounted Kindle)",
    )
    args = parser.parse_args(argv)
    return run(args.source, Path(__file__).resolve().parent)


if __name__ == "__main__":
    sys.exit(main())
