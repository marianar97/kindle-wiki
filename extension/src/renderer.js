// Port of sync.py's rendering semantics. Block IDs must stay byte-compatible:
// sha1("title|type|location|text") truncated to 12 hex chars, where a missing
// location renders as "None" exactly like Python's f-string did.

export async function clipId(clip) {
  const key = `${clip.title}|${clip.type}|${clip.location ?? "None"}|${clip.text}`;
  const digest = await crypto.subtle.digest("SHA-1", new TextEncoder().encode(key));
  return [...new Uint8Array(digest)]
    .map((b) => b.toString(16).padStart(2, "0"))
    .join("")
    .slice(0, 12);
}

export function slugify(title) {
  const slug = title
    .toLowerCase()
    .replace(/[^a-z0-9]+/g, "-")
    .replace(/^-+|-+$/g, "");
  return slug || "untitled";
}

export const GENERATED_NOTE =
  "<!-- GENERATED by Kindle Wiki Sync — edits are overwritten on every sync -->";

const TYPE_RANK = { highlight: 0, note: 1 };

export async function assignIds(clips) {
  return Promise.all(clips.map(async (clip) => ({ ...clip, id: await clipId(clip) })));
}

export function dedupe(clips) {
  const seen = new Set();
  const result = [];
  for (const clip of clips) {
    if (seen.has(clip.id)) continue;
    seen.add(clip.id);
    result.push(clip);
  }
  return result;
}

function locationStart(clip) {
  if (!clip.location) return 0;
  return parseInt(clip.location.split("-")[0], 10) || 0;
}

export function sortClips(clips) {
  return [...clips].sort(
    (a, b) => locationStart(a) - locationStart(b) || TYPE_RANK[a.type] - TYPE_RANK[b.type]
  );
}

function metaLine(clip) {
  const parts = [clip.type];
  if (clip.type === "highlight" && clip.color) parts.push(clip.color);
  if (clip.location) parts.push(`loc. ${clip.location}`);
  return parts.join(" · ");
}

function renderClip(clip) {
  if (clip.type === "highlight") {
    const quoted = clip.text.split("\n").map((line) => `> ${line}`).join("\n");
    return `${quoted}\n>\n> — ${metaLine(clip)} ^${clip.id}`;
  }
  return `Note: ${clip.text}\n— ${metaLine(clip)} ^${clip.id}`;
}

export function renderBook(title, author, clips, syncedOn) {
  const lines = [
    "---",
    `title: ${JSON.stringify(title)}`,
    `author: ${author ? JSON.stringify(author) : "null"}`,
    `last_synced: ${syncedOn}`,
    "---",
    GENERATED_NOTE,
    "",
    `# ${title}`,
  ];
  if (author) lines.push(`*${author}*`);
  lines.push("", "## Highlights", "");
  const body = clips.map(renderClip).join("\n\n");
  return `${lines.join("\n")}\n${body}\n`;
}
